import { test, expect } from '@playwright/test'

test('Docker production UI requires login; no anonymous sample topology', async ({ page }) => {
  const response = await page.goto('/')
  expect(response?.status()).toBe(200)
  await expect(page.getByRole('heading', { name: 'ورود به مرکز مدیریت شبکه' })).toBeVisible()
  await expect(page.getByLabel('ایمیل')).toBeVisible()
  await expect(page.getByLabel('رمز عبور')).toBeVisible()
  await expect(page.getByText('DEMO DATA · NOT LIVE')).toHaveCount(0)
  await page.goto('/topology')
  await expect(page.getByRole('heading', { name: 'ورود به مرکز مدیریت شبکه' })).toBeVisible()
  await page.screenshot({ path: '../../../resources/ux-review/docker-pilot-login.png', fullPage: true })
  const anonymous = await page.request.get('/api/v1/auth/me')
  expect(anonymous.status()).toBe(401)
  const csrf = await page.request.get('/api/v1/auth/csrf')
  expect(csrf.status()).toBe(200)
  expect((await csrf.json()).token.length).toBeGreaterThan(10)
  const graph = await page.request.get('/api/v1/topology/graph?siteId=lab')
  expect(graph.status()).toBe(401)
  const health = await page.request.get('/health/live')
  expect(health.status()).toBe(200)
  const ready = await page.request.get('/health/ready')
  expect(ready.status()).toBe(503)
})
