// Read-only browser QA of the deployed docked topology page. No scan writes.
import { readFileSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { chromium, expect } from '@playwright/test'

const root = resolve(import.meta.dirname, '../../../..')
const env = Object.fromEntries(readFileSync(resolve(root, 'infra/local/.env'), 'utf8')
  .split(/\r?\n/).map(line => line.trim())
  .filter(line => line && !line.startsWith('#') && line.includes('='))
  .map(line => {
    const i = line.indexOf('=')
    const value = line.slice(i + 1).trim()
    return [line.slice(0, i), /^['"].*['"]$/.test(value) ? value.slice(1, -1) : value]
  }))
if (!env.INFRAGRAPH_ADMIN_EMAIL || !env.INFRAGRAPH_ADMIN_PASSWORD)
  throw new Error('Local pilot admin credentials unavailable')
const dir = resolve(root, 'infra/local/_publish/runtime')
mkdirSync(dir, { recursive: true })
const browser = await chromium.launch({channel: 'msedge'})
const ctx = await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1600,height:950}})
const page = await ctx.newPage()
const errors=[]
const failedRequests=[]
page.on('response', response => { if (response.status() >= 400) failedRequests.push({status:response.status(),url:response.url().replace(/^https:\/\/localhost:8443/, '')}) })
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => {if(message.type()==='error')errors.push(`${message.text()} @ ${message.location().url}`)})
try {
 const base='https://localhost:8443'
 await page.goto(base+'/topology',{waitUntil:'domcontentloaded',timeout:20000})
 await expect(page.getByRole('heading',{name:'ورود به مرکز مدیریت شبکه'})).toBeVisible()
 await page.getByLabel('ایمیل').fill(env.INFRAGRAPH_ADMIN_EMAIL)
 await page.getByLabel('رمز عبور').fill(env.INFRAGRAPH_ADMIN_PASSWORD)
 await page.getByRole('button',{name:'ورود',exact:true}).click()
 await expect(page.getByRole('heading',{name:'توپولوژی شبکه'})).toBeVisible()
 const left=page.getByTestId('topology-left-dock')
 const right=page.getByTestId('topology-right-dock')
 const bottom=page.getByTestId('topology-bottom-dock')
 const stage=page.getByTestId('topology-stage')
 await expect(left).toBeVisible()
 await expect(right).toBeVisible()
 await expect(bottom).toBeVisible()
 await expect(stage).toBeVisible()
 await expect(stage.locator('input, select, .scan-panel, .access-form')).toHaveCount(0)
 await page.getByTestId('topology-left-rail').getByRole('button',{name:'بازکردن تب اسکن'}).click()
 await expect(left.getByText('کشف فعال IP و پایش تغییرات')).toBeVisible()
 await expect(left.getByText('SignalR متصل')).toBeVisible({timeout:20000})
 await page.getByTestId('topology-right-rail').getByRole('button',{name:'بازکردن تب لایه‌ها'}).click()
 await expect(right.getByText('شبکه زمینه')).toBeVisible()
 await expect(page.getByTestId('topology-bottom-rail').getByRole('button',{name:'بازکردن تب وضعیت و شواهد'})).toHaveAttribute('aria-pressed','true')
 const nodes=await stage.locator('.react-flow__node').count()
 const edges=await stage.locator('.react-flow__edge').count()
 const counts=await bottom.locator('.ig-dock-metrics').innerText()
 const boxes=await Promise.all([left,stage,right,bottom].map(loc=>loc.boundingBox()))
 if(!boxes.every(Boolean)||boxes[0].x+boxes[0].width>boxes[1].x+10||
   boxes[1].x+boxes[1].width>boxes[2].x+10||boxes[3].y<boxes[1].y+boxes[1].height-10)
   throw new Error('Dock geometry overlaps live center')
 await page.screenshot({path:resolve(dir,'docked-topology-live-desktop.png'),fullPage:true,animations:'disabled'})
 await page.getByTestId('topology-left-rail').getByRole('button',{name:'بازکردن تب اسکن'}).click()
 await expect(left).toHaveCount(0)
 await page.getByTestId('topology-left-rail').getByRole('button',{name:'بازکردن تب اسکن'}).click()
 await expect(page.getByTestId('topology-left-dock')).toBeVisible()
 await page.getByTestId('topology-left-dock').getByRole('button',{name:'جمع‌کردن پنل چپ · کاوش'}).click()
 await page.getByTestId('topology-right-dock').getByRole('button',{name:'جمع‌کردن پنل راست · بازرسی'}).click()
 await page.getByTestId('topology-bottom-dock').getByRole('button',{name:'جمع‌کردن پنل پایین · عملیات'}).click()
 await expect(page.getByTestId('topology-left-rail')).toBeVisible()
 await expect(page.getByTestId('topology-right-rail')).toBeVisible()
 await expect(page.getByTestId('topology-bottom-rail')).toBeVisible()
 await page.screenshot({path:resolve(dir,'docked-topology-live-collapsed-rails.png'),fullPage:true,animations:'disabled'})
 await page.getByRole('button',{name:'بازکردن تب اسکن'}).click()
 await expect(page.getByTestId('topology-left-rail').getByRole('button',{name:'بازکردن تب اسکن'})).toHaveAttribute('aria-pressed','true')

 await page.goto(base+'/monitoring/discovery',{waitUntil:'domcontentloaded'})
 await expect(page.getByTestId('monitoring-discovery')).toBeVisible()
 await expect(page.getByRole('table',{name:'نودهای کشف‌شده شبکه'})).toBeVisible()
 const discovered=await page.locator('.discovery-result-count').innerText()
 await page.screenshot({path:resolve(dir,'monitoring-discovery-live-desktop.png'),fullPage:true,animations:'disabled'})
 await expect(page.getByRole('navigation',{name:'ناوبری اصلی'}).getByRole('link',{name:/Discovery/})).toBeVisible()
 await page.getByRole('link',{name:/بازکردن استودیو نقشه/}).click()
 await expect(page.getByTestId('topology-studio')).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 await expect(stage).toBeVisible()
 await expect(page.getByTestId('topology-left-dock')).toHaveCount(0)
 await expect(page.getByTestId('topology-right-dock')).toHaveCount(0)
 await expect(page.getByTestId('topology-bottom-dock')).toHaveCount(0)
 await page.getByTestId('topology-left-rail').getByRole('button',{name:'بازکردن تب اسکن'}).click()
 await expect(page.getByTestId('topology-left-dock')).toBeVisible()
 await expect(page.getByTestId('topology-left-dock').getByText('کشف فعال IP و پایش تغییرات')).toBeVisible()
 await page.getByTestId('topology-left-rail').getByRole('button',{name:'بازکردن تب اسکن'}).click()
 await expect(page.getByTestId('topology-left-dock')).toHaveCount(0)
 await page.screenshot({path:resolve(dir,'docked-topology-live-mobile.png'),fullPage:true,animations:'disabled'})
 const noOverflow=await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth+1)
 if(!noOverflow) throw new Error('Mobile document has horizontal overflow')
 console.log('DISCOVERY_RESULT '+discovered)
 console.log('HTTP_FAILURE_DIAGNOSTICS '+JSON.stringify(failedRequests))
 if(errors.length && failedRequests.some(r => r.status >= 500)) throw new Error('Server errors: '+JSON.stringify(failedRequests))
 console.log(JSON.stringify({result:'PASS',site:'lan',viewport:'1600x950',nodes,edges,
  statusCounts:counts.replace(/\n/g,' '),dockRects:boxes.map(box=>({x:Math.round(box.x),y:Math.round(box.y),width:Math.round(box.width),height:Math.round(box.height)})),
  screenshot:resolve(dir,'docked-topology-live-desktop.png'),errors,scanPacketsSent:0}))
} finally {await browser.close()}